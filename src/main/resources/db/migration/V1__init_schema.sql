--   - 엔티티와 1:1 - Hibernate ddl-auto=validate 가 기동 시 대조한다 (테이블·열 존재, 타입, 널 여부)
--   - 제약 이름은 schema.md 의 이름 그대로 - 후속 마이그레이션이 이름으로 참조할 수 있게 고정
--   - FK 는 RESTRICT(기본) - 연쇄 삭제의 주체는 서비스 (zip 파일이 DB 밖에 있어 DB cascade 만으로는 파일이 남는다)
--   - PostgreSQL 은 FK 인덱스를 자동 생성하지 않음 - 조회 경로의 인덱스를 명시
--   - 시각 열은 timestamptz(6) = 자바 Instant(UTC), enum 은 varchar + CHECK (EnumType.STRING)
